export function getDummyMembersForUnit(
  unitId: string,
  unitCode: string,
  unitName: string,
  level: string,
  targetCount: number,
  headOfUnit?: {
    id?: string
    name?: string
    title?: string
    email?: string
    avatar?: string
  } | null,
): OrgMember[] {
  const count = Math.max(1, targetCount || 4)
  const list: OrgMember[] = []

  // Prepend leader if available
  if (headOfUnit && headOfUnit.name) {
    list.push({
      id: headOfUnit.id || `emp-${unitId}-0`,
      name: headOfUnit.name,
      nik: `EMP-${unitCode.replace(/[^A-Z0-9]/g, '')}-001`,
      title: headOfUnit.title || `Head of ${unitName}`,
      email:
        headOfUnit.email || `${headOfUnit.name.toLowerCase().replace(/[^a-z]/g, '')}@company.com`,
      avatar: headOfUnit.avatar,
      status: 'active',
      joinDate: '15 Jan 2021',
    })
  }

  // Generate the remaining members to match EXACTLY targetCount
  const remaining = count - list.length
  for (let i = 0; i < remaining; i++) {
    const seq = list.length + 1
    const fIdx = (Math.abs(hashString(unitId)) + i * 3) % FIRST_NAMES.length
    const lIdx = (Math.abs(hashString(unitId)) + i * 7 + 5) % LAST_NAMES.length
    const firstName = FIRST_NAMES[fIdx]
    const lastName = LAST_NAMES[lIdx]
    const fullName = `${firstName} ${lastName}`
    const cleanCode = unitCode.replace(/[^A-Z0-9]/g, '')
    const nik = `EMP-${cleanCode.slice(0, 4)}-${String(seq).padStart(3, '0')}`

    const titles = TITLES_BY_LEVEL[level] || TITLES_BY_LEVEL.position
    const title =
      level === 'position'
        ? i === 0
          ? unitName
          : `${unitName} (Staff)`
        : `${titles[i % titles.length]} - ${unitName}`

    list.push({
      id: `emp-${unitId}-${seq}`,
      name: fullName,
      nik: nik,
      title: title,
      email: `${firstName.toLowerCase()}.${lastName.toLowerCase()}@company.com`,
      status: i % 8 === 0 ? 'probation' : i % 12 === 0 ? 'contract' : 'active',
      joinDate: `${(i % 28) + 1} Apr 2022`,
    })
  }

  return list.slice(0, count)
}

function hashString(str: string): number {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i)
    hash |= 0
  }
  return hash
}

export function getDummyMembersForNode(node: OrgNode): OrgMember[] {
  return getDummyMembersForUnit(
    node.id,
    node.code,
    node.name,
    node.level,
    node.totalEmployees,
    node.headOfUnit,
  )
}
